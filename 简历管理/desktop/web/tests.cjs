const assert = require("node:assert/strict");
const {esc,emptySnapshot,selectData,latestReview,pageSlice}=require("./app.js");
const s=emptySnapshot();
s.candidates=[{id:"c1",name:"示例甲",source:"内推"},{id:"c2",name:"示例乙",source:"平台"},{id:"c3",name:"储备候选人"}];
s.jobs=[{id:"j1",title:"机械工程师",department:"研发部",month:"2026-10"},{id:"j2",title:"工艺工程师",department:"制造部",month:"2026-11"}];
s.applications=[{id:"a1",candidate_id:"c1",job_id:"j1",month:"2026-10",status:"二面"},{id:"a2",candidate_id:"c2",job_id:"j2",month:"2026-11",status:"初面"}];
s.interviews=[{id:"i1",application_id:"a1",round:2},{id:"i2",application_id:"a2",round:1}];
s.reviews=[{id:"r1",application_id:"a1",score:80,is_stale:false},{id:"r2",application_id:"a1",score:90,is_stale:false},{id:"r3",application_id:"a1",score:100,is_stale:true}];
assert.deepEqual(selectData(s,"2026-10","").candidates.map(c=>c.id),["c1"],"候选人月份由关联投递确定");
assert.deepEqual(selectData(s,"2026-10","").interviews.map(i=>i.id),["i1"],"面试月份由投递确定");
assert.equal(selectData(s,"","研发部").candidates[0].id,"c1","可按关联部门搜索");
assert.equal(selectData(s,"","示例甲").jobs[0].id,"j1","可按候选人搜索关联岗位");
assert.equal(selectData(s,"","").candidates.length,3,"无月份时保留储备候选人");
assert.equal(latestReview(s,"a1").id,"r2","最新有效审核排除过期结果");
assert.equal(latestReview(s,"absent"),undefined);
assert.equal(esc('<img src=x onerror="x">'),"&lt;img src=x onerror=&quot;x&quot;&gt;");
const many=Array.from({length:14},(_,i)=>({id:`c${i+10}`}));
const first=pageSlice(many,"test-page",6);
assert.equal(first.items.length,6,"分页每页固定数量");
assert.equal(first.pages,3,"分页页数正确");
assert.equal(pageSlice(many,"test-page",6,99).page,3,"超出页码回到最后一页");
assert.equal(pageSlice(many,"test-page",6,0).page,1,"无效页码回到第一页");
console.log("12 web logic checks passed");
